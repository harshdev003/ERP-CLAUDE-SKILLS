#!/usr/bin/env python3
"""Refresh the snapshot of IntelligenceService's stored prompter names.

`tests/test_is_prompter_names.py` holds AINative's conversation lists to this
snapshot. CI cannot reach IntelligenceService, so the snapshot is what brings a
new name in: refresh it after IntelligenceService adds, renames or merges a
prompter, and the test then says which AINative lists still need it.

The snapshot holds, from `src/config.js` at the IntelligenceService default branch:

  * every `prompt.<key>` stored name: `name`, its `legacyNames`, and any
    experiment arm's `name` (an arm should never set one, but one that did
    would store rows under it);
  * `conversation.allowedTypes`, the conversation types the apps can start;
  * `conversation.prompterAliases`.

It reads the files at that ref through `git archive`, so the checkout's working
tree and branch are never touched, and evaluates `config.js` with Node in a
temp dir (it requires only `package.json` and `config/*.json`).

    python3 scripts/refresh-is-prompter-names.py [--repo PATH] [--ref REF] [--check] [--no-fetch]

`--repo` defaults to `$INTELLIGENCE_SERVICE_PATH`, then
`~/Development/Aura/Services/IntelligenceService`. `--ref` defaults to the
remote's default branch. `--check` writes nothing and reports drift.

Exit: 0 written, or no drift with `--check` · 1 drift with `--check` · 2 could not run.
"""
from __future__ import annotations

import argparse
import io
import json
import os
import subprocess
import sys
import tarfile
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SNAPSHOT = REPO_ROOT / "tests" / "fixtures" / "is_prompter_names.json"
DEFAULT_REPO = Path.home() / "Development" / "Aura" / "Services" / "IntelligenceService"
FILES = ["src/config.js", "package.json", "config"]

EXTRACT_JS = r"""
const c = require(process.argv[1]);
const prompters = {};
for (const [key, p] of Object.entries(c.prompt || {})) {
  if (!p || typeof p !== 'object' || !p.name) continue;
  const names = [p.name, ...(p.legacyNames || [])];
  for (const exp of Object.values(p.experiments || {})) {
    for (const arm of Object.values(exp || {})) if (arm && arm.name) names.push(arm.name);
  }
  prompters[key] = [...new Set(names)].sort();
}
const conv = c.conversation || {};
process.stdout.write(JSON.stringify({
  prompters,
  conversationTypes: [...(conv.allowedTypes || [])].sort(),
  prompterAliases: conv.prompterAliases || {},
}));
"""


class RefreshError(RuntimeError):
    pass


def _git(repo: Path, *args: str, binary: bool = False):
    r = subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=not binary)
    if r.returncode != 0:
        err = r.stderr.decode() if binary else r.stderr
        raise RefreshError(f"git {' '.join(args)}: {err.strip()}")
    return r.stdout


def default_ref(repo: Path) -> str:
    try:
        return _git(repo, "symbolic-ref", "--short", "refs/remotes/origin/HEAD").strip()
    except RefreshError:
        return "origin/master"


def extract(repo: Path, ref: str) -> dict:
    commit = _git(repo, "rev-parse", ref).strip()
    committed = _git(repo, "show", "-s", "--format=%cs", commit).strip()
    archive = _git(repo, "archive", "--format=tar", commit, *FILES, binary=True)
    with tempfile.TemporaryDirectory() as tmp:
        with tarfile.open(fileobj=io.BytesIO(archive)) as tar:
            tar.extractall(tmp, filter="data")
        env = {k: v for k, v in os.environ.items() if k != "GOOGLE_APPLICATION_CREDENTIALS"}
        env["NODE_ENV"] = "test"
        try:
            r = subprocess.run(["node", "-e", EXTRACT_JS, str(Path(tmp, "src", "config.js"))],
                               capture_output=True, text=True, env=env, cwd=tmp)
        except FileNotFoundError as e:
            raise RefreshError("node is not installed") from e
        if r.returncode != 0:
            raise RefreshError(f"evaluating config.js failed: {r.stderr.strip()[-500:]}")
    data = json.loads(r.stdout)
    if not data["prompters"]:
        raise RefreshError("config.js declared no prompters; refusing to write an empty snapshot")
    return {
        "_comment": "Generated by scripts/refresh-is-prompter-names.py. Do not edit by hand.",
        "source": {"repo": "AuraHealth/IntelligenceService", "ref": ref, "commit": commit,
                   "committed": committed},
        **data,
    }


def diff(old: dict, new: dict) -> list[str]:
    lines = []
    old_p, new_p = old.get("prompters", {}), new["prompters"]
    for key in sorted(set(old_p) | set(new_p)):
        a, b = set(old_p.get(key, [])), set(new_p.get(key, []))
        for name in sorted(b - a):
            lines.append(f"+ {key}: {name}")
        for name in sorted(a - b):
            lines.append(f"- {key}: {name}")
    for field in ("conversationTypes", "prompterAliases"):
        if old.get(field) != new[field]:
            lines.append(f"~ {field}: {json.dumps(old.get(field))} -> {json.dumps(new[field])}")
    return lines


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--repo", type=Path,
                   default=Path(os.environ.get("INTELLIGENCE_SERVICE_PATH") or DEFAULT_REPO))
    p.add_argument("--ref")
    p.add_argument("--check", action="store_true", help="Report drift; write nothing.")
    p.add_argument("--no-fetch", action="store_true", help="Skip `git fetch origin`.")
    args = p.parse_args()
    try:
        if not (args.repo / ".git").exists():
            raise RefreshError(f"no IntelligenceService checkout at {args.repo} (pass --repo)")
        if not args.no_fetch:
            _git(args.repo, "fetch", "--quiet", "origin")
        ref = args.ref or default_ref(args.repo)
        new = extract(args.repo, ref)
    except RefreshError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    old = json.loads(SNAPSHOT.read_text(encoding="utf-8")) if SNAPSHOT.exists() else {}
    changes = diff(old, new)
    head = f"IntelligenceService {new['source']['commit'][:8]} ({new['source']['committed']})"
    if args.check:
        if changes:
            print(f"DRIFT: the snapshot differs from {head}:")
            print("\n".join(changes))
            print("Run without --check to refresh it, then run tests/test_is_prompter_names.py.")
            return 1
        print(f"OK: the snapshot matches {head}")
        return 0
    SNAPSHOT.write_text(json.dumps(new, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(f"wrote {SNAPSHOT.relative_to(REPO_ROOT)} from {head}")
    print("\n".join(changes) if changes else "no name changes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
