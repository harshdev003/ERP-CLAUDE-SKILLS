#!/usr/bin/env python3
"""`notion_rest.py` — the `rich_text()` markdown parser.

The defects this guards
-----------------------
Two constructs that appear routinely in the markdown our knowledge skills write
were silently dropped, because the parser was a single flat regex pass:

1. **Inline code.** Backticks passed straight through as literal characters. This
   was visible in production on `Guide/Index`, where every path entry rendered as
   a raw ``` `Procedures/Engineering/PR Process` ``` instead of a code span — that
   page is regenerated by `shared:harvest-knowledge` through this parser.

2. **A link nested inside bold.** `**[label](url)**` emitted a bold run whose text
   was the literal string ``[label](https://…)`` — no link at all. Hit while
   inserting a bullet into the `Procedures/Engineering` Pages list.

Why it needs a test rather than a look
--------------------------------------
Both failures are **silent in the direction that matters**: the page is created,
the API returns 200, and the markdown still reads correctly to whoever wrote it.
Only a human opening the page notices, and by then the write has shipped. Nothing
raises, so no amount of exercising the happy path surfaces either one — which is
exactly how they lasted 18 copies deep.

The fix is recursion (bold and link fold their attribute into whatever their
content parses to), so the interesting cases are the **combinations**, and the
property worth asserting is negative: no run's text may still contain raw
markdown. A test that only checked "does bold work" and "does a link work"
independently passes against the broken parser.

Runs against **every** copy of `notion_rest.py` in `plugins/` (the file is
duplicated per skill under Architecture principle 1), so a copy that diverges
behaviourally fails here even when the byte-diff has been reconciled.
"""
from __future__ import annotations

import pathlib
import unittest

from reader_harness import load_reader, script_paths

NOTION_REST_PATHS = script_paths("notion_rest.py")


def flags(run: dict) -> set[str]:
    return {k for k, v in (run.get("annotations") or {}).items() if v}


def link_of(run: dict):
    return (run["text"].get("link") or {}).get("url")


def text_of(run: dict) -> str:
    return run["text"]["content"]


class RichTextCase(unittest.TestCase):
    """Per-copy assertions. `path` is injected by load_tests."""

    path: pathlib.Path

    def setUp(self):
        self.mod = load_reader(self.path, siblings=())
        self.rich_text = self.mod.rich_text

    # -- the two shipped defects ------------------------------------------------

    def test_italic_becomes_an_italic_annotation(self):
        """Single-asterisk italic. It shipped into AI Knowledge pages as literal
        asterisks twice before the parser learned it — the same silent shape the
        module docstring describes for the flat-pass bug."""
        runs = self.rich_text("*italic*")
        self.assertEqual(1, len(runs))
        self.assertEqual(text_of(runs[0]), "italic")
        self.assertEqual(flags(runs[0]), {"italic"})

    def test_bold_italic_carries_both(self):
        runs = self.rich_text("***both***")
        self.assertEqual("both", "".join(text_of(r) for r in runs))
        self.assertEqual(flags(runs[0]), {"bold", "italic"})

    def test_bold_is_not_parsed_as_italic(self):
        """`***` then `**` then `*`. Wrong order turns bold into an italic run
        wrapping a stray asterisk, which reads almost right and is not."""
        runs = self.rich_text("**bold**")
        self.assertEqual("bold", "".join(text_of(r) for r in runs))
        self.assertEqual(flags(runs[0]), {"bold"})

    def test_a_lone_asterisk_in_prose_is_not_emphasis(self):
        """The strictness is the point: italic needs a non-space character just
        inside each delimiter, so prose and SQL survive untouched."""
        for text in ("a * b", "SELECT * FROM t", "3-5 *", "* leading"):
            runs = self.rich_text(text)
            self.assertEqual(text, "".join(text_of(r) for r in runs), text)
            for r in runs:
                self.assertNotIn("italic", flags(r), text)

    def test_one_gap_warns_once(self):
        """Review finding. `rich_text` recurses to fold bold, italic and link
        attributes, and each level saw the same leftover markers — so a single
        gap was reported as several. Only the outermost call reports."""
        import io, contextlib
        for text in ("**a ~~b~~ c**", "*x ~~y~~*", "[~~a~~](u)", "~~plain~~",
                     "***a ~~b~~***"):
            buf = io.StringIO()
            with contextlib.redirect_stderr(buf):
                self.rich_text(text)
            lines = [l for l in buf.getvalue().splitlines() if l.strip()]
            self.assertEqual(1, len(lines), f"{text}: {lines}")

    def test_dispatch_is_by_delimiters_not_prefix(self):
        """Found by an exhaustive sweep over delimiter combinations, not by review.

        The bold alternative can match a token that *starts* with three asterisks
        — `**` + `*a` + `**` spans all of `***a**` — so dispatching on the prefix
        sent it to the bold-italic handler, which slices `tok[3:-3]`. On a
        six-character token that is the empty string, and the content was silently
        destroyed: `***a**` rendered as nothing at all."""
        for text in ("***a**", "**a***", "***a*", "*a**", "****a****",
                     "***[x](u)**"):
            runs = self.rich_text(text)
            out = "".join(text_of(r) for r in runs)
            self.assertIn("a" if "a" in text else "x", out,
                          f"{text!r} destroyed its content -> {out!r}")

    def test_field_name_wildcards_are_left_alone_and_silent(self):
        """Strings drawn from the live teamspace. Engineering prose is full of
        prefix/suffix wildcards, and an earlier revision warned on every one of
        them — ~30 false positives against zero true positives over 11,177 real
        blocks, which is how a warning gets muted."""
        import io, contextlib
        for text in ("The users.premium* fields on the Aura API user row",
                     "the ai* tenure columns are propagated",
                     "Refer to the corresponding *State field",
                     "any track* helper", "videoSubscription* in the payout export",
                     "plaintext .env.<env> files are gitignored (.env*)",
                     "Every test method needs at least one XCTAssert* call.",
                     "room glob aurie-room-*", "config.models.content.* thresholds",
                     "payout.paidListens*", "braintrust.log* calls",
                     "The genuinely dead one is alacarte* ($79 in July)."):
            buf = io.StringIO()
            with contextlib.redirect_stderr(buf):
                runs = self.rich_text(text)
            self.assertEqual(text, "".join(text_of(r) for r in runs), text)
            self.assertEqual("", buf.getvalue(), text)
            for r in runs:
                self.assertNotIn("italic", flags(r), text)

    def test_clean_input_is_silent(self):
        import io, contextlib
        for text in ("*italic*", "**bold**", "***both***", "*Really?*",
                     "*[l](u)*", "plain text"):
            buf = io.StringIO()
            with contextlib.redirect_stderr(buf):
                self.rich_text(text)
            self.assertEqual("", buf.getvalue(), text)

    def test_globs_and_paths_are_not_italic(self):
        """Review finding. `*.*`, `*/*` and `plugins/*/skills/*` are globs, not
        emphasis — and this failure cannot be caught downstream, because the
        delimiters get consumed so no leftover asterisk survives to warn about.
        `plugins/*/skills/*` rendered as `plugins//skills/` with two slashes gone;
        the live teamspace already contains one such pattern (`*-alert/*`)."""
        for text in ("*.*", "*/*", "plugins/*/skills/*", "plugins/*/agents/*.md",
                     "*-alert/*", "a/*/b"):
            runs = self.rich_text(text)
            self.assertEqual(text, "".join(text_of(r) for r in runs), text)
            for r in runs:
                self.assertNotIn("italic", flags(r), text)

    def test_italic_boundary_is_asymmetric_on_purpose(self):
        """Only the OPENING is restricted to alphanumeric-or-construct-delimiter;
        the closer merely has to be non-space.

        Review finding: every glob that motivated the rule opens with `/`, `.` or
        `-`, so testing the opening alone rejects all of them — while a symmetric
        rule also rejects ordinary emphasis ending in punctuation and ships its
        markers into the page, which is the leak this parser exists to close."""
        for text in ("*Really?*", "*done.*", "*Wait!*", "*x, y*"):
            runs = self.rich_text(text)
            self.assertEqual(text[1:-1], "".join(text_of(r) for r in runs), text)
            self.assertIn("italic", flags(runs[0]), text)
        for text in ("*-x-*", "*.x.*", "*/x/*"):
            runs = self.rich_text(text)
            self.assertEqual(text, "".join(text_of(r) for r in runs), text)
        self.assertEqual(flags(self.rich_text("*a*")[0]), {"italic"})
        self.assertEqual(flags(self.rich_text("*`code`*")[0]), {"code", "italic"})

    def test_italic_does_not_steal_a_bold_delimiter(self):
        """Review finding on the commit that introduced italic. Without a
        `(?<!\\*)`/`(?!\\*)` guard the italic closer consumes the opening mark of a
        following `**` run, so the bold silently becomes italic — a wrong answer
        that reads almost right, which is the failure class this parser exists to
        avoid."""
        runs = self.rich_text("*x**y**")
        bolded = [r for r in runs if "bold" in flags(r)]
        self.assertEqual(1, len(bolded), "y must be bold, not italic")
        self.assertEqual("y", text_of(bolded[0]))
        for r in runs:
            self.assertNotIn("italic", flags(r))

    def test_emphasis_spanning_emphasis_resolves_the_inner_run(self):
        """Markdown does not define `*a **b** c*`. The parser does not guess: the
        bold resolves and the outer delimiters stay literal rather than producing
        a confident wrong nesting."""
        runs = self.rich_text("*a **b** c*")
        bolded = [r for r in runs if "bold" in flags(r)]
        self.assertEqual(1, len(bolded))
        self.assertEqual("b", text_of(bolded[0]))

    def test_dunder_is_not_treated_as_underline(self):
        """Notion has no markdown form for underline, so `__x__` is not a construct
        to warn about — and treating it as one fires on every `__init__`."""
        import io, contextlib
        buf = io.StringIO()
        with contextlib.redirect_stderr(buf):
            runs = self.rich_text("call __init__ then __repr__")
        self.assertEqual("call __init__ then __repr__",
                         "".join(text_of(r) for r in runs))
        self.assertEqual("", buf.getvalue())

    def test_strikethrough_still_warns(self):
        import io, contextlib
        buf = io.StringIO()
        with contextlib.redirect_stderr(buf):
            self.rich_text("~~gone~~")
        self.assertIn("~~gone~~", buf.getvalue())

    def test_asterisk_inside_a_code_span_stays_literal(self):
        runs = self.rich_text("`x*y`")
        self.assertEqual(text_of(runs[0]), "x*y")
        self.assertEqual(flags(runs[0]), {"code"})

    def test_mixed_bold_and_italic_in_one_string(self):
        runs = self.rich_text("**a** and *b*")
        self.assertEqual("a and b", "".join(text_of(r) for r in runs))
        self.assertEqual(flags(runs[0]), {"bold"})
        self.assertEqual(flags(runs[-1]), {"italic"})

    def test_italic_link_keeps_both(self):
        runs = self.rich_text("*[label](https://x)*")
        self.assertEqual(text_of(runs[0]), "label")
        self.assertEqual(flags(runs[0]), {"italic"})
        self.assertEqual(link_of(runs[0]), "https://x")

    def test_code_span_becomes_a_code_annotation(self):
        runs = self.rich_text("a `code` span")
        self.assertEqual([text_of(r) for r in runs], ["a ", "code", " span"])
        self.assertEqual(flags(runs[1]), {"code"})
        self.assertEqual(flags(runs[0]), set())

    def test_link_nested_in_bold_is_a_bold_link(self):
        runs = self.rich_text("**[Release Process](https://example.com/x)**")
        self.assertEqual(len(runs), 1)
        self.assertEqual(text_of(runs[0]), "Release Process")
        self.assertEqual(flags(runs[0]), {"bold"})
        self.assertEqual(link_of(runs[0]), "https://example.com/x")

    # -- the negative property that a per-construct test would miss -------------

    def test_no_run_ever_contains_raw_markdown(self):
        samples = [
            "**[a](https://x)**",
            "[**a**](https://x)",
            "[`a`](https://x)",
            "**`a`**",
            "plain **b** and [l](https://x) and `c`",
            "**bold** then `code` then [link](https://x)",
        ]
        for s in samples:
            with self.subTest(markdown=s):
                for run in self.rich_text(s):
                    t = text_of(run)
                    self.assertNotIn("**", t)
                    self.assertNotIn("](", t)
                    self.assertNotIn("`", t)

    # -- nesting, both directions ----------------------------------------------

    def test_bold_inside_a_link(self):
        runs = self.rich_text("[**a**](https://x)")
        self.assertEqual(len(runs), 1)
        self.assertEqual(text_of(runs[0]), "a")
        self.assertEqual(flags(runs[0]), {"bold"})
        self.assertEqual(link_of(runs[0]), "https://x")

    def test_code_inside_a_link(self):
        runs = self.rich_text("[`eng:release-version`](https://x)")
        self.assertEqual(len(runs), 1)
        self.assertEqual(text_of(runs[0]), "eng:release-version")
        self.assertEqual(flags(runs[0]), {"code"})
        self.assertEqual(link_of(runs[0]), "https://x")

    def test_code_inside_bold_keeps_both(self):
        runs = self.rich_text("**`forced`**")
        self.assertEqual(len(runs), 1)
        self.assertEqual(text_of(runs[0]), "forced")
        self.assertEqual(flags(runs[0]), {"bold", "code"})

    # -- code spans are leaves -------------------------------------------------

    def test_markdown_inside_a_code_span_stays_literal(self):
        """Backticks are literal in Markdown; `**` inside them is not an annotation."""
        runs = self.rich_text("a `**not bold**` b")
        self.assertEqual([text_of(r) for r in runs], ["a ", "**not bold**", " b"])
        self.assertEqual(flags(runs[1]), {"code"})

    def test_unbalanced_backtick_is_passed_through(self):
        runs = self.rich_text("unbalanced ` backtick")
        self.assertEqual(len(runs), 1)
        self.assertEqual(text_of(runs[0]), "unbalanced ` backtick")
        self.assertEqual(flags(runs[0]), set())

    # -- unchanged behaviour ---------------------------------------------------

    def test_plain_bold_and_plain_link_still_work(self):
        b = self.rich_text("**b**")
        self.assertEqual((text_of(b[0]), flags(b[0])), ("b", {"bold"}))
        l = self.rich_text("[l](https://x)")
        self.assertEqual((text_of(l[0]), link_of(l[0])), ("l", "https://x"))
        self.assertEqual(flags(l[0]), set())

    def test_plain_text_is_one_unannotated_run(self):
        runs = self.rich_text("just words")
        self.assertEqual(len(runs), 1)
        self.assertEqual(text_of(runs[0]), "just words")
        self.assertEqual(flags(runs[0]), set())

    def test_empty_string_yields_one_empty_run(self):
        runs = self.rich_text("")
        self.assertEqual(len(runs), 1)
        self.assertEqual(text_of(runs[0]), "")

    # -- the production line that exposed defect 1 -----------------------------

    def test_guide_index_entry_shape(self):
        runs = self.rich_text(
            "`Procedures/Engineering/Release Process` — How a repo gets released."
        )
        self.assertEqual(text_of(runs[0]), "Procedures/Engineering/Release Process")
        self.assertEqual(flags(runs[0]), {"code"})
        self.assertNotIn("`", "".join(text_of(r) for r in runs))

    def test_concatenated_text_drops_only_the_delimiters(self):
        runs = self.rich_text("see **[the page](https://x)** or `run --force`")
        self.assertEqual("".join(text_of(r) for r in runs),
                         "see the page or run --force")


def load_tests(loader, tests, pattern):
    """One RichTextCase subclass per copy, so a diverging copy fails by name."""
    suite = unittest.TestSuite()
    if not NOTION_REST_PATHS:
        raise AssertionError("no notion_rest.py found under plugins/")
    for path in NOTION_REST_PATHS:
        rel = path.relative_to(pathlib.Path(__file__).resolve().parent.parent)
        name = "RichText_" + str(rel).replace("/", "_").replace(".py", "")
        cls = type(name, (RichTextCase,), {"path": path})
        suite.addTests(loader.loadTestsFromTestCase(cls))
    return suite


if __name__ == "__main__":
    unittest.main()
