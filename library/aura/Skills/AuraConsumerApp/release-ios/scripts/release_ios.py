def preflight(s: State, *, needs_build: bool) -> list[str]:
    """Everything that can be checked in seconds, checked before an archive that
    takes tens of minutes. Returns blocking problems."""
    problems: list[str] = []

    blocked = phase_block_reason(s)
    if blocked:
        problems.append(blocked)

    if not shutil.which("gh"):
        problems.append("`gh` is not installed — needed for the PR and the merge.")
    elif run(["gh", "auth", "status"], check=False).returncode != 0:
        problems.append("`gh` is not authenticated. Run `gh auth login`.")

    # A `tagged-unreleased` resume only calls `gh release create`. It cuts no
    # branch and pushes no tag, so both guards below would be blocking a step
    # they cannot protect — and the tag one would block it by definition.
    if s.phase != "tagged-unreleased":
        dirty = git("status", "--porcelain")
        if dirty:
            problems.append(
                "Working tree is not clean. The release branch is cut from "
                f"{REMOTE}/{DEFAULT_BRANCH} in this checkout, and the bump commit must "
                "carry the version change and nothing else.\n"
                + "\n".join(f"      {line}" for line in dirty.splitlines()[:10])
            )

        if s.tag_remote:
            problems.append(f"Tag {s.tag} already exists on origin. Bump the build number.")
        elif s.tag_local and s.phase != "merged-untagged":
            # Before the merge, a local tag is someone else's leftover and the
            # version should move. At `merged-untagged` it is the expected residue
            # of a tag that was created and then failed to push — blocking there
            # would strand a release whose binary is already on TestFlight and
            # whose bump is already on main, with "bump the build number" as the
            # only advice, which is exactly the wrong move. step_tag re-verifies
            # the existing tag points at the merge commit before pushing it.
            problems.append(f"Tag {s.tag} already exists locally. Bump the build number.")

    if not needs_build:
        return problems

    # The .xcodeproj is generated and gitignored, so every build starts by
    # regenerating it. Without xcodegen, `make proj` fails inside the lane —
    # after the branch is cut and the bump is committed.
    if not shutil.which("xcodegen"):
        problems.append(
            "`xcodegen` is not on PATH. The .xcodeproj is generated from project.yml, so "
            "`make proj` runs at the start of every build.\n"
            "      Install it with `make install-xcodegen` (brew install xcodegen)."
        )

    if run(["bundle", "exec", "fastlane", "--version"], cwd=FASTLANE_DIR, check=False).returncode != 0:
        problems.append(
            "`bundle exec fastlane` does not run in fastlane/. Run `bundle install` there "
            "(gems must land in the Ruby named by .ruby-version)."
        )

    problems.extend(check_env_config(s.env, s.warnings))

    # An archive that gets 30 seconds in and dies on signing has still cost a
    # clean checkout and a bump commit, so check credentials up front.
    # Ordered before the route-specific checks: in a worktree the missing
    # fastlane/.env is what *decides* the route, so it has to be settled first.
    worktree_env = check_worktree_asc_env(s.warnings)
    problems.extend(worktree_env)
    problems.extend(check_asc_partial())
    problems.extend(check_asc_token(s.warnings))
    problems.extend(check_signing(s.warnings, announce_xcode_route=not worktree_env))

    return problems


