@dataclass
class State:
    env: str
    version: str
    build: str
    tag: str
    branch: str
    baseline_version: str
    baseline_build: str
    level: str | None
    local_branch_sha: str | None
    remote_branch_sha: str | None
    tag_local: bool
    tag_remote: bool
    github_release: bool
    pr: dict | None
    phase: str
    main_sha: str = ""
    last_tag: str | None = None
    warnings: list[str] = field(default_factory=list)

    @property
    def built_commit(self) -> str | None:
        """The commit the binary was archived from — the bump commit at the tip
        of the release branch. Prefer the remote copy: once pushed it is the
        durable record, and a local branch can be reset or deleted."""
        return self.remote_branch_sha or self.local_branch_sha


def fetch() -> None:
    """Refresh branches, then tags.

    The two are separate and the tag fetch is non-fatal on purpose: `git fetch
    --tags` exits non-zero on the whole operation rather than skipping the one
    ref that disagrees with origin, and this repo carries 158 legacy tags any of
    which could drift. Nothing here trusts the local tag list for a decision that
    matters — whether the release tag already exists is answered by
    `git ls-remote`, which asks origin directly.
    """
    run(["git", "fetch", "--prune", REMOTE])
    result = run(["git", "fetch", "--tags", REMOTE], check=False)
    if result.returncode != 0:
        clobbered = [
            line.split()[2]
            for line in (result.stderr or "").splitlines()
            if "would clobber existing tag" in line and len(line.split()) > 2
        ]
        if clobbered:
            log(
                "Note: local tags disagree with origin and were left alone: "
                + ", ".join(clobbered[:8])
                + (" …" if len(clobbered) > 8 else "")
            )


def rev_or_none(ref: str) -> str | None:
    result = run(["git", "rev-parse", "--verify", "--quiet", ref], check=False)
    return result.stdout.strip() or None


def remote_branch_sha(branch: str) -> str | None:
    line = git("ls-remote", "--heads", REMOTE, f"refs/heads/{branch}")
    return line.split()[0] if line else None


def remote_tag_exists(tag: str) -> bool:
    return bool(git("ls-remote", "--tags", REMOTE, f"refs/tags/{tag}"))


def github_release_exists(tag: str) -> bool:
    return run(["gh", "release", "view", tag], check=False).returncode == 0


def find_pr(branch: str) -> dict | None:
    prs = gh_json(
        "pr", "list",
        "--head", branch,
        "--state", "all",
        "--json", "number,state,url,mergeStateStatus,mergeCommit,headRefOid,title",
        "--limit", "10",
    )
    if not prs:
        return None
    return sorted(prs, key=lambda p: p["number"])[-1]


def derive_state(env: str, level: str | None, version: str | None, build: str | None) -> State:
    fetch()

    main_sha = rev_or_none(f"{REMOTE}/{DEFAULT_BRANCH}")
    if not main_sha:
        raise ReleaseError(
            f"{REMOTE}/{DEFAULT_BRANCH} is not resolvable. Run `git fetch {REMOTE}` and retry."
        )

    baseline_version, baseline_build = read_version_at(f"{REMOTE}/{DEFAULT_BRANCH}")

    if version:
        target_version = version
        target_build = build or "1"
    elif level:
        target_version, target_build = next_version(baseline_version, baseline_build, level)
        if build:
            target_build = build
    else:
        raise ReleaseError("Give either --level or --version.")

    if not VERSION_RE.match(target_version):
        raise ReleaseError(f"Invalid version {target_version!r} — expected X.Y.Z.")
    if not BUILD_RE.match(str(target_build)):
        raise ReleaseError(f"Invalid build {target_build!r} — expected a positive integer.")

    tag = f"{target_version}-{target_build}"
    branch = f"release/{tag}"
    tag_on_origin = remote_tag_exists(tag)

    state = State(
        env=env,
        version=target_version,
        build=str(target_build),
        tag=tag,
        branch=branch,
        baseline_version=baseline_version,
        baseline_build=baseline_build,
        level=level,
        local_branch_sha=rev_or_none(f"refs/heads/{branch}"),
        remote_branch_sha=remote_branch_sha(branch),
        tag_local=bool(rev_or_none(f"refs/tags/{tag}")),
        tag_remote=tag_on_origin,
        github_release=github_release_exists(tag) if tag_on_origin else False,
        pr=find_pr(branch),
        phase="",
        main_sha=main_sha,
        last_tag=latest_release_tag(exclude=tag),
    )

    state.phase = _phase(state)
    _add_warnings(state)
    return state


def _phase(s: State) -> str:
    if s.tag_remote:
        return "released" if s.github_release else "tagged-unreleased"
    if s.pr and s.pr["state"] == "MERGED":
        return "merged-untagged"
    if s.pr and s.pr["state"] == "OPEN":
        return "pr-open"
    if s.pr and s.pr["state"] == "CLOSED":
        return "pr-closed"
    if s.remote_branch_sha:
        return "branch-pushed"
    if s.local_branch_sha:
        return "bumped"
    return "fresh"


def phase_block_reason(s: State) -> str | None:
    """A phase that no amount of pre-flight fixing can proceed from.

    Returned as a pre-flight *problem* rather than a warning so `plan` and `run`
    agree. A plan that green-lights a release `run` will not perform is worse
    than no plan.
    """
    if s.phase != "pr-closed":
        return None
    return (
        f"PR #{s.pr['number']} for {s.branch} was closed without merging, so this "
        "release cannot proceed.\n"
        f"      Reopen {s.pr['url']}, or delete the branch (local and remote) and "
        "re-run to cut a fresh build."
    )


def unfinished_release_tag(s: State) -> str | None:
    """A release that reached its tag and stopped before publishing.

    The version `main` declares IS the last release that landed, so its tag is
    the only one worth checking. A `--level` run computes its version from that
    same baseline, so it walks straight past the unfinished release into a new
    one — and the "just re-run the same command" resume never reaches it.

    Only the BARE tag counts. A legacy `v`-prefixed tag with no GitHub release
    describes every release cut before this skill — none of them can be resumed
    into `gh release create`, because `derive_state` resolves `--version X --build
    N` to the bare tag and would cut a fresh build instead of publishing. Flagging
    those would attach a remedy that does not work to 157 historical releases.
    Back-filling them is a deliberate one-off, not a per-run warning.
    """
    candidate = f"{s.baseline_version}-{s.baseline_build}"
    if candidate == s.tag:
        return None  # this run IS that release; the phase already says so
    if remote_tag_exists(candidate):
        return None if github_release_exists(candidate) else candidate
    # No bare tag. If the legacy form is there, this is a pre-skill release and
    # nothing is outstanding. If neither exists, `main` declares a version that was
    # never tagged — a bump that merged and then stopped, which is the phase the
    # `--level` resume trap hits hardest.
    if remote_tag_exists(f"v{candidate}"):
        return None
    return candidate


def _add_warnings(s: State) -> None:
    # Only when cutting a brand-new computed version: with an explicit --version
    # the operator is already naming a specific release, and the extra lookups
    # would be paid on every invocation for nothing.
    if s.level and s.phase == "fresh":
        pending = unfinished_release_tag(s)
        if pending:
            version, _, build = pending.rpartition("-")
            resume = f"--env {s.env} --version {version} --build {build}"
            if remote_tag_exists(pending):
                detail = (
                    f"{pending} is tagged on {REMOTE} with no GitHub release — an earlier "
                    "release stopped before publishing"
                )
            else:
                detail = (
                    f"{REMOTE}/{DEFAULT_BRANCH} declares {version} ({build}) but nothing is "
                    f"tagged {pending} — a version bump merged and the release stopped "
                    "before tagging"
                )
            s.warnings.append(
                f"{detail}, and this run cuts {s.tag} past it rather than finishing it.\n"
                f"           Check it with:   status {resume}\n"
                f"           Finish it with:  run {resume}"
            )

    target = sort_key(s.tag)
    baseline = sort_key(f"{s.baseline_version}-{s.baseline_build}")
    if target <= baseline:
        s.warnings.append(
            f"{s.tag} is not ahead of what {REMOTE}/{DEFAULT_BRANCH} declares "
            f"({s.baseline_version} ({s.baseline_build})). App Store Connect rejects a "
            "build number already used for a version."
        )
    if s.env == "dev":
        s.warnings.append(
            "env=dev still bumps main and cuts a release tag, same as prod — "
            "the tag namespace is shared."
        )


# ---------------------------------------------------------------------------
# Environment configuration
#
# `make env-<env> release` (Scripts/switch-env.sh) symlinks
# Secrets.release.xcconfig at Secrets.<env>.xcconfig and copies
# GoogleService-Info_<Env>.plist over GoogleService-Info.plist. The `release`
# lane runs it as step 0 and aborts if either source is missing — which would be
# a failure after the branch was cut and the bump committed, so check up front.
#
# Both destinations are gitignored, so the swap cannot dirty the tree and trip
# the clean-tree assertions later in the run.
# ---------------------------------------------------------------------------


def in_worktree() -> bool:
    """True in a linked worktree, where the gitignored config files are absent
    until they are copied across from the main checkout."""
    common = run(["git", "rev-parse", "--git-common-dir"], check=False).stdout.strip()
    own = run(["git", "rev-parse", "--git-dir"], check=False).stdout.strip()
    if not (common and own):
        return False
    return (REPO_ROOT / common).resolve() != (REPO_ROOT / own).resolve()


def main_checkout_root() -> Path | None:
    """The main checkout's working tree, when this is a linked worktree.

    `--git-common-dir` points at the main checkout's `.git`, so its parent is that
    working tree. Returns None for a bare or otherwise unusual layout, where there
    is no working tree to copy gitignored files out of.
    """
    common = run(["git", "rev-parse", "--git-common-dir"], check=False).stdout.strip()
    if not common:
        return None
    git_dir = (REPO_ROOT / common).resolve()
    if git_dir.name != ".git":
        return None
    return git_dir.parent


def env_config_sources(env: str) -> tuple[Path, Path]:
    return (
        CONFIG_DIR / f"Secrets.{env}.xcconfig",
        CONFIG_DIR / f"GoogleService-Info_{env.capitalize()}.plist",
    )


def check_env_config(env: str, warnings: list[str]) -> list[str]:
    xcconfig, plist = env_config_sources(env)
    missing = [p for p in (xcconfig, plist) if not p.is_file()]
    if missing:
        listed = "\n".join(f"        - {p.relative_to(REPO_ROOT)}" for p in missing)
        if in_worktree():
            # A linked worktree never has these — they are gitignored, so `git
            # worktree add` cannot bring them across. .claude/rules/config.md
            # covers the fix; the plist must be a real copy because xcodebuild
            # drops symlinks from Copy Bundle Resources.
            remedy = (
                "      This is a linked worktree, so the gitignored config was not checked "
                "out.\n"
                "      Copy it from the main checkout (see .claude/rules/config.md) — the "
                "plist\n"
                "      must be a real copy, not a symlink, or xcodebuild omits it from the "
                "bundle."
            )
        else:
            remedy = (
                "      These are gitignored per-developer files. Copy the xcconfig from "
                "Secrets.xconfig.sample\n"
                "      and fill it in, and download the plist from the Firebase console."
            )
        return [
            f"The {env} build configuration is incomplete — `make env-{env} release` "
            "would abort in the lane's step 0:\n"
            f"{listed}\n" + remedy
        ]

    # Bugsnag symbol upload reads BUGSNAG_API_KEY out of Secrets.release.xcconfig,
    # which by then is the symlink to this env's file. A missing key is not fatal
    # — the lane logs and continues — but it means the release ships with no
    # symbolication, which is worth knowing before rather than after.
    try:
        text = xcconfig.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return []
    if not re.search(r"^\s*BUGSNAG_API_KEY\s*=\s*\S", text, re.MULTILINE):
        warnings.append(
            f"{xcconfig.relative_to(REPO_ROOT)} has no BUGSNAG_API_KEY. The dSYM upload "
            "will fail, and the lane only logs that — crashes for this build would not "
            "symbolicate."
        )
    return []


