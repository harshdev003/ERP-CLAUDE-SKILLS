def read_version_at(ref: str | None) -> tuple[str, str]:
    """(version, build) as `ref` declares them — the working tree when None.

    Reads the app target, then asserts the extension target agrees. They are
    written together by the `updateVersion` lane, so a divergence means someone
    hand-edited one of them, and shipping it would mean an app and an extension
    with different CFBundleShortVersionStrings.
    """
    if ref is None:
        text = (REPO_ROOT / PROJECT_YML_REL).read_text(encoding="utf-8")
    else:
        text = git("show", f"{ref}:{PROJECT_YML_REL}")

    versions = {target: _extract_version(text, target) for target in VERSION_TARGETS}
    distinct = set(versions.values())
    if len(distinct) != 1:
        detail = "; ".join(f"{t}={v} ({b})" for t, (v, b) in versions.items())
        raise ReleaseError(
            f"project.yml targets disagree on the version at {ref or 'the working tree'}: "
            f"{detail}. Fix them to match before releasing."
        )
    return versions[APP_TARGET]


def _extract_version(text: str, target: str) -> tuple[str, str]:
    """MARKETING_VERSION and CURRENT_PROJECT_VERSION for one target in project.yml.

    Hand-rolled rather than parsed with PyYAML, which is not in the macOS system
    Python and cannot be assumed on a release host. That is safe only because the
    parse is narrow: find the target's block by indentation, then require exactly
    one of each key inside it. Two matches means the file grew config-specific
    overrides and this needs revisiting — so it raises rather than picking one.
    """
    lines = text.splitlines()

    try:
        top = next(i for i, line in enumerate(lines) if line.rstrip() == "targets:")
    except StopIteration:
        raise ReleaseError("project.yml has no top-level `targets:` block.")

    start = None
    for i in range(top + 1, len(lines)):
        line = lines[i]
        if line.strip() and not line.startswith(" "):
            break  # a new top-level key — out of `targets:`
        if line.rstrip() == f"  {target}:":
            start = i
            break
    if start is None:
        raise ReleaseError(f"project.yml has no `{target}` target under `targets:`.")

    # Target keys sit at two spaces and their contents at four or more, so the
    # first later non-blank line indented less than four ends the block.
    end = len(lines)
    for i in range(start + 1, len(lines)):
        if lines[i].strip() and not lines[i].startswith("    "):
            end = i
            break
    block = lines[start:end]

    def one(key: str) -> str:
        hits = [line for line in block if re.match(rf"^\s+{key}:\s*\S", line)]
        if len(hits) != 1:
            raise ReleaseError(
                f"Expected exactly one `{key}` under target `{target}` in project.yml, "
                f"found {len(hits)}."
            )
        return hits[0].split(":", 1)[1].strip().strip("'\"")

    return one("MARKETING_VERSION"), one("CURRENT_PROJECT_VERSION")


def next_version(current: str, current_build: str, level: str) -> tuple[str, str]:
    major, minor, patch = (int(p) for p in current.split("."))
    if level == "build":
        # Holds the version and increments the build — how a version whose binary
        # was rejected or superseded gets re-shipped.
        return current, str(int(current_build) + 1)
    if level == "major":
        major, minor, patch = major + 1, 0, 0
    elif level == "minor":
        minor, patch = minor + 1, 0
    else:
        patch += 1
    return f"{major}.{minor}.{patch}", "1"


def sort_key(tag: str) -> tuple:
    for pattern in (TAG_RE, LEGACY_TAG_RE):
        m = pattern.match(tag)
        if m:
            return (int(m[1]), int(m[2]), int(m[3]), int(m[4]))
    return (0, 0, 0, 0)


def is_ancestor(ref: str, of: str) -> bool:
    return run(["git", "merge-base", "--is-ancestor", ref, of], check=False).returncode == 0


def latest_release_tag(exclude: str | None = None, ancestor_of: str | None = None) -> str | None:
    """The most recent release tag reachable from `ancestor_of` (default: the tip
    of the default branch).

    Ordered by tag creation date, NOT by version number, and it accepts both the
    bare and the legacy `v`-prefixed form. Chronological order plus an ancestry
    check gives the tag the previous release actually cut, which is what a
    release-notes range needs — and it stays correct across the tag-format change
    rather than treating the first bare tag as having no predecessor.

    `ancestor_of` is what makes that true for a back-fill as well as for a fresh
    release. Anchored on main's tip it answers "the newest release", which is the
    wrong end of the range when the release being described is an older one:
    every tag cut since would be reachable, and the notes would list the work
    that shipped *after* it.
    """
    anchor = ancestor_of or f"{REMOTE}/{DEFAULT_BRANCH}"
    ordered = git(
        "for-each-ref", "--sort=-creatordate", "--format=%(refname:short)", "refs/tags"
    ).splitlines()
    for tag in ordered:
        if tag == exclude or not (TAG_RE.match(tag) or LEGACY_TAG_RE.match(tag)):
            continue
        if is_ancestor(tag, anchor):
            return tag
    return None


