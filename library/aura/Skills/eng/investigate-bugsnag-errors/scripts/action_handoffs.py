"""Builds the structured payloads for Mode 4 — action handoffs.

Mode 4 is orchestrated by Claude (the model), not Python — the CLI
builds a draft payload and prints it; Claude executes the actual
side-effect (Slack post, Linear card create, fixer-agent spawn) after
explicit user confirmation.

Two payload shapes today:

- `linear_card` — title / description (markdown) / label hints, plus an
  app-family-derived team hint. Consumed by `shared:add-linear-issues`.
- `slack_reply` — concise summary suitable for posting in a thread.
  Consumed by the Slack MCP.

The "fixer-agent handoff" mentioned in the PROD-1659 spec is a
chained next-step rather than a Mode-4 sub-action: after a Linear
card lands, the user (or Claude) runs `eng:linear-task <ticket-id>`,
which is the canonical entrypoint for spawning `eng:implementation-
agent`. We don't reinvent that orchestration here.
"""
from __future__ import annotations

import datetime as dt
import json
import os
import re
from typing import Any

from normalize import parse_frames
from projects import lookup as project_lookup

SKILL_ID = "eng:investigate-bugsnag-errors"


def _skill_version() -> str:
    """Read this skill's semver from the sibling SKILL.md `metadata.version`.

    Scoped to the `metadata:` block so a `version:` token elsewhere (e.g. in the
    description) can't shadow it. Empty string if unreadable.
    """
    try:
        text = open(os.path.join(os.path.dirname(__file__), os.pardir, "SKILL.md"),
                    encoding="utf-8").read()
    except OSError:
        return ""
    fm = re.match(r"^---\n(.*?)\n---", text, re.DOTALL)
    fm = fm.group(1) if fm else text
    block = re.search(r"(?m)^metadata:[ \t]*\n((?:[ \t]+\S.*\n?)+)", fm)
    if not block:
        return ""
    ver = re.search(r'''(?m)^[ \t]+version:[ \t]*["']?([^"'\s]+)["']?[ \t]*$''', block.group(1))
    return ver.group(1) if ver else ""


def _slack_footer() -> str:
    """The Tools/Slack attribution footer for a prepared reply — versioned + dated,
    so the ``--prepare-slack-reply`` payload is post-ready without further edits."""
    ver = _skill_version()
    ident = f"{SKILL_ID}:{ver}" if ver else SKILL_ID
    today = dt.datetime.now(dt.timezone.utc).date().isoformat()
    return f"_Generated by `{ident}` · {today}_"


# --- helpers ---------------------------------------------------------

def _truncate(s: str, n: int) -> str:
    if not s:
        return ""
    return s if len(s) <= n else s[:n - 1] + "…"


def _bugsnag_url(slug: str | None, error_id: str | None) -> str:
    if not slug or not error_id:
        return ""
    return f"https://app.bugsnag.com/aura-health/{slug}/errors/{error_id}"


def _safe_int(v: Any) -> int:
    try:
        return int(v)
    except (TypeError, ValueError):
        return 0


def _format_frames_markdown(event: dict[str, Any] | None,
                            stack: str, max_frames: int = 5) -> list[str]:
    """Render the top in-project frames as markdown bullets."""
    frames = parse_frames((event or {}).get("stacktrace"), stack)
    in_proj = [f for f in frames if f.in_project] or frames
    out: list[str] = []
    for f in in_proj[:max_frames]:
        loc = f"{f.file}{':' + str(f.line) if f.line else ''}"
        out.append(f"- `{loc}` → `{f.method}`")
    return out


# --- Linear card -----------------------------------------------------

def build_linear_card(error: dict[str, Any], event: dict[str, Any] | None,
                      project_slug: str | None,
                      code_context: str | None = None) -> dict[str, Any]:
    """Build a draft Linear card payload from a Bugsnag focused error.

    `code_context` is an optional Mode 2.5 report — the orchestrator passes
    it in if Mode 2.5 ran earlier. We splice it under a "## Code context"
    heading.

    Returns a dict consumable by `shared:add-linear-issues`. The orchestrator
    is responsible for resolving `team_hint` to an actual Linear team
    (prompts the user when ambiguous).
    """
    family = project_lookup(project_slug)
    cls = error.get("error_class") or "<unknown>"
    msg = error.get("message") or ""
    error_id = error.get("id") or ""
    bugsnag_url = _bugsnag_url(project_slug, error_id)
    events_count = _safe_int(error.get("events") or error.get("events_count"))
    users_count = _safe_int(error.get("users") or error.get("users_count"))
    first_seen = error.get("first_seen") or "?"
    last_seen = error.get("last_seen") or "?"

    # Title: short and scan-friendly. Truncated message keeps it readable in lists.
    short_msg = _truncate(msg, 80)
    title = f"[{family.family}] {cls}"
    if short_msg:
        title = f"{title}: {short_msg}"
    title = _truncate(title, 120)  # Linear soft-caps titles around this length

    # Description: markdown with the canonical sections
    desc_lines: list[str] = [
        f"**Bugsnag error:** [{cls}]({bugsnag_url})" if bugsnag_url
        else f"**Bugsnag error:** {cls}",
        "",
        "## Error",
        f"- **Class:** {cls}",
        f"- **Message:** {msg}" if msg else "- **Message:** _(none)_",
        f"- **Events:** {events_count}  ·  **Users affected:** {users_count}",
        f"- **First seen:** {first_seen}",
        f"- **Last seen:** {last_seen}",
        "",
        "## App family",
        f"**{family.family}** — stack: `{family.stack}`"
        + (f", repo: [`{family.repo}`](https://github.com/{family.repo})" if family.repo else ", repo: TBD"),
    ]

    frame_lines = _format_frames_markdown(event, family.stack)
    if frame_lines:
        desc_lines.append("")
        desc_lines.append("## Top stacktrace frames (latest event)")
        desc_lines.extend(frame_lines)

    if code_context and not code_context.startswith("[Mode 2.5 skipped]"):
        desc_lines.append("")
        desc_lines.append("## Code context")
        desc_lines.append("")
        desc_lines.append(code_context.strip())

    # Suggested labels — orchestrator strips any the team doesn't have.
    labels = ["bugsnag", "bug"]
    family_label = family.family.lower().replace(" / ", "-").replace(" ", "-").replace("(", "").replace(")", "")
    if family_label != "unknown":
        labels.append(family_label)

    return {
        "title": title,
        "description": "\n".join(desc_lines),
        "labels": labels,
        # Free-form hint; orchestrator resolves to a real team or prompts the user.
        "team_hint": _suggest_team(family.family),
        # Useful metadata for the orchestrator's confirmation prompt:
        "_bugsnag_url": bugsnag_url,
        "_project_slug": project_slug,
        "_error_id": error_id,
    }


def _suggest_team(family_label: str) -> str:
    """Map an app-family label to a free-form team suggestion.

    Deliberately fuzzy — the orchestrator (or `shared:add-linear-issues`) is
    responsible for resolving against the live Linear team list and prompting
    the user when the suggestion doesn't match exactly.
    """
    low = family_label.lower()
    if "aurie" in low:
        return "AI"  # Aurie projects file to the AI team
    if "mobile" in low:
        return "Mobile"
    if "web" in low or "embed" in low or "desktop" in low:
        return "Engineering"
    return "Engineering"


# --- Slack reply -----------------------------------------------------

def build_slack_reply(error: dict[str, Any], project_slug: str | None,
                      code_context: str | None = None) -> dict[str, Any]:
    """Build a draft Slack reply for an alerts-bugsnag thread.

    Slack mrkdwn syntax differs slightly from Linear markdown: `*bold*`
    rather than `**bold**`, no headers, plain `<url|text>` links. We
    return the body as Slack-flavoured mrkdwn so the orchestrator can
    post it via the Slack MCP without extra transformation.
    """
    family = project_lookup(project_slug)
    cls = error.get("error_class") or "<unknown>"
    msg = error.get("message") or ""
    error_id = error.get("id") or ""
    bugsnag_url = _bugsnag_url(project_slug, error_id)
    events_count = _safe_int(error.get("events") or error.get("events_count"))
    users_count = _safe_int(error.get("users") or error.get("users_count"))
    last_seen = error.get("last_seen") or "?"

    short_msg = _truncate(msg, 200)
    lines: list[str] = [
        f"*{cls}* — _{family.family}_",
    ]
    if short_msg:
        lines.append(f"> {short_msg}")
    lines.append(
        f"`{events_count}` events  ·  `{users_count}` users affected  ·  last seen `{last_seen}`"
    )
    if bugsnag_url:
        lines.append(f"<{bugsnag_url}|Open in Bugsnag>")

    if code_context and not code_context.startswith("[Mode 2.5 skipped]"):
        # Indent the code context as a Slack quote block for visual separation.
        lines.append("")
        lines.append("*Code context:*")
        for cc_line in code_context.strip().splitlines():
            lines.append(f"> {cc_line}")

    # One Tools/Slack attribution footer, separated by a blank line (versioned +
    # dated), so the payload is post-ready as the SKILL.md promises.
    lines.append("")
    lines.append(_slack_footer())

    return {
        "text": "\n".join(lines),
        "_bugsnag_url": bugsnag_url,
        "_project_slug": project_slug,
        "_error_id": error_id,
    }


# --- top-level helpers used by investigate.py ------------------------

def fetch_and_build_linear_card(client, *, error_id: str,
                                project_slug: str | None,
                                code_context: str | None = None) -> str:
    """Fetch error + latest event, then emit JSON for the orchestrator."""
    error = client.get_error(error_id)
    if not project_slug:
        project_slug = error.get("project_slug")
    events = client.list_events(error_id, per_page=1)
    event = events[0] if events else None
    payload = build_linear_card(error, event, project_slug, code_context=code_context)
    return json.dumps(payload, indent=2)


def fetch_and_build_slack_reply(client, *, error_id: str,
                                project_slug: str | None,
                                code_context: str | None = None) -> str:
    """Fetch error, then emit JSON for the orchestrator."""
    error = client.get_error(error_id)
    if not project_slug:
        project_slug = error.get("project_slug")
    payload = build_slack_reply(error, project_slug, code_context=code_context)
    return json.dumps(payload, indent=2)
