FILE_VERSION = 1


def uid_prefix(uid: str) -> str:
    """A uid prefix that still tells users apart: for a provider id (`google:112...`) the 8
    characters come after the provider, which stays as a label. Canonical:
    report-conversation-patterns/scripts/sample.py (docs/canonical-sources.md)."""
    uid = uid or ""
    if ":" in uid:
        provider, _, rest = uid.partition(":")
        return f"{provider}:{rest[:8]}"
    return uid[:8]
# The daily practices, as flagged in conversation.firstMessageContext (the only three in prod).
PRACTICES = {"morning": "Morning check-in", "evening": "Evening wind-down", "walking": "Walking practice"}


def load_export(path, uid, part, include_onboarding=False):
    """The conversations of one user from eng:query-user-export-data's file, as the export shape
    `{"conversations": [{"id", "turns"}]}`. `part` is "conversations" (daily practices left out:
    they have their own document) or "checkins" (only those). Refuses a file of another version,
    section or user."""
    try:
        data = json.loads(Path(path).expanduser().read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        raise SystemExit(f"Could not read the export file ({type(error).__name__}).") from error
    if not isinstance(data, dict) or data.get("version") != FILE_VERSION:
        raise SystemExit(f"The export file is not version {FILE_VERSION}; refusing to guess its shape.")
    if data.get("entity") != "conversations":
        raise SystemExit(f"The export file holds {data.get('entity')!r}, not 'conversations'.")
    if data.get("userIdPrefix") != uid_prefix(uid):
        raise SystemExit("The export file is for another user (its uid prefix does not match --uid).")
    if not isinstance(data.get("rows"), list):
        raise SystemExit("The export file has no rows list.")
    kept, practice_counts, left_out = [], {}, {"practice": 0, "onboarding": 0, "removed": 0}
    for c in data["rows"]:
        if c.get("removed"):  # removed by the user in the app, as the app shows it
            left_out["removed"] += 1
            continue
        practice = c.get("practice")
        if practice:
            practice_counts[practice] = practice_counts.get(practice, 0) + 1
        if (part == "checkins") != bool(practice):
            left_out["practice"] += part != "checkins"
            continue
        if c.get("isOnboarding") and not include_onboarding:
            left_out["onboarding"] += 1
            continue
        kept.append({"id": c.get("id"), "practice": practice, "turns": c.get("messages") or [],
                     "rating": c.get("rating"), "feedback": c.get("feedback")})
    return {"conversations": kept, "practice_counts": practice_counts, "left_out": left_out}


class TimezoneError(Exception):
    """The user's timezone could not be read."""


def fetch_timezone(host, token, uid):
    """The user's `timezone` from UserService `GET /users/<uid>`; only that field is kept."""
    request = urllib.request.Request(
        f"{host.rstrip('/')}/users/{urllib.parse.quote(uid, safe='')}",
        headers={"Authorization": f"Bearer {token}", "User-Agent": user_agent()})
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            return (json.loads(response.read().decode("utf-8")) or {}).get("timezone")
    except urllib.error.HTTPError as error:
        raise TimezoneError(f"GET /users/:userId answered {error.code}") from error
    except (urllib.error.URLError, ValueError, OSError) as error:
        raise TimezoneError(f"GET /users/:userId failed: {type(error).__name__}") from error


def flatten(export):
    """Turn the API's per-conversation shape into the flat turn list the renderer wants."""
    rows = []
    for conversation in export.get("conversations", []):
        for turn in conversation.get("turns", []):
            rows.append({
                "conversationId": conversation.get("id"),
                "practice": conversation.get("practice"),
                "createdAt": turn.get("createdAt"),
                "id": turn.get("id"),
                "message": turn.get("message"),
                "role": turn.get("role"),
                "rating": turn.get("rating"),
                "feedback": turn.get("feedback"),
                "conv_feedback": {"rating": conversation.get("rating"), "feedback": conversation.get("feedback")},
            })
    return rows


