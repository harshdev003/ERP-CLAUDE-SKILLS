def plural(n, one, many=None):
    return f"{n:,} {one if n == 1 else (many or one + 's')}"


def num(v):
    return f"{v:,}" if isinstance(v, int) else str(v)


def header_rule(title, span):
    text = f"{title} · {span}".replace("\\", "\\\\").replace('"', '\\"')
    return f'@page {{ @top-left {{ content: "{text}"; }} }}'


def prepared_line():
    return "Prepared on " + datetime.date.today().strftime("%B %-d, %Y")


def time_span(a, b):
    """'4:07 PM – 4:14 PM', or a single time when both ends are the same minute."""
    s, e = a.strftime("%-I:%M %p"), b.strftime("%-I:%M %p")
    return s if s == e else f"{s} &ndash; {e}"


def month_id(d):
    return f"m-{d.year}-{d.month:02d}"


def toc_html(months):
    """A contents page: one clickable line per month (Chrome cannot compute page numbers)."""
    return ('<div class="toc"><h2>Contents</h2>'
            + "".join(f'<div><a href="#{month_id(m)}">{m.strftime("%B %Y")}</a><span>{plural(n, "day")}</span></div>'
                      for m, n in months)
            + "</div>")


def group_rows(rows: list[dict], tz: ZoneInfo):
    """Bucket turns by the user's LOCAL day, then by conversation within the day.

    Returns (days, conv_days, stats). `conv_days` maps a conversation to every
    local day it was active on, which is what drives the continuation markers.
    """
    for r in rows:
        r["dt"] = datetime.datetime.fromisoformat(r["createdAt"]).astimezone(tz)
    rows.sort(key=lambda r: r["dt"])

    days: OrderedDict = OrderedDict()
    for r in rows:
        days.setdefault(r["dt"].date(), OrderedDict()).setdefault(r["conversationId"], []).append(r)

    spans: dict = {}
    for r in rows:
        spans.setdefault(r["conversationId"], []).append(r["dt"])
    conv_days = {cid: sorted({d.date() for d in ds}) for cid, ds in spans.items()}

    stats = {
        "days": len(days),
        "conversations": len({r["conversationId"] for r in rows}),
        "user_turns": sum(1 for r in rows if r["role"] == "user"),
        "aurie_turns": sum(1 for r in rows if r["role"] == "assistant"),
        "first": min(days),
        "last": max(days),
    }
    return days, conv_days, stats


def continuation_bits(alldays: list, d) -> list[str]:
    """Human phrases for a conversation that spans more than the current day."""
    if len(alldays) < 2:
        return []
    i = alldays.index(d)
    bits = []
    if i > 0:
        bits.append("continued from " + alldays[i - 1].strftime("%b %-d"))
    if i < len(alldays) - 1:
        bits.append("continues " + alldays[i + 1].strftime("%b %-d"))
    return bits


def shorten(msg: str, full_len: int, where: str) -> str:
    return (
        msg[:500].rsplit(" ", 1)[0]
        + f"…\n\n[Pasted content — {full_len:,} characters. Shown in full in the {where}.]"
    )


def md_safe(text: str) -> str:
    """Neutralise block-level Markdown inside a message body.

    Users paste documents into the chat, and a pasted `# Heading` or `---` rule
    would otherwise be emitted as real document structure — hijacking the day
    hierarchy the export is built on. Escaping the leading marker keeps every
    character on the page while stopping it from acting as structure. Inline
    marks (bold, italic, links) are left alone; they cannot break the outline.
    """
    out = []
    for line in text.split("\n"):
        line = re.sub(r"^(\s*)(#{1,6})(\s|$)", r"\1\\\2\3", line)
        line = re.sub(r"^(\s*)(-{3,}|_{3,}|\*{3,}|={3,})\s*$", r"\1\\\2", line)
        out.append(line)
    return "\n".join(out)


