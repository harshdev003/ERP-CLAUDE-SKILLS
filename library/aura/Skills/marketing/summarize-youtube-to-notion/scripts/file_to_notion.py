#!/usr/bin/env python3
"""Create a Growth Readings page in Notion via REST (no MCP).

Reads the composed Markdown summary from a file, discovers the target database
schema at runtime, converts the body to Notion blocks, and POSTs a new page.
REST-only — requires NOTION_TOKEN (see CLAUDE.md "Notion REST integration").
There is no MCP fallback (same posture as `product:record-ideas`).

Usage:
    python3 file_to_notion.py \
        --markdown-file body.md \
        --title "Video title" \
        --source-url "https://www.youtube.com/watch?v=..." \
        --date 2026-05-26 \
        --icon 🎧

Add --dry-run to print the converted block payload without writing.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from notion_rest import notion, make_title, make_rich_text, make_date  # noqa: E402
from notion_blocks import markdown_to_blocks  # noqa: E402


def _skill_version() -> str:
    """This skill's semver from the sibling SKILL.md `metadata.version` (scoped to
    the metadata block). Empty string if unreadable."""
    try:
        text = open(os.path.join(os.path.dirname(__file__), os.pardir, "SKILL.md"),
                    encoding="utf-8").read()
    except OSError:
        return ""
    fm = re.match(r"^---\n(.*?)\n---", text, re.DOTALL)
    fm = fm.group(1) if fm else text
    block = re.search(r"(?m)^metadata:[ \t]*\n((?:[ \t]+\S.*\n?)+)", fm)
    if not block:
        return ""
    m = re.search(r'''(?m)^[ \t]+version:[ \t]*["']?([^"'\s]+)["']?[ \t]*$''', block.group(1))
    return m.group(1) if m else ""


def _stamp_footer_version(body_md: str) -> str:
    """Deterministically stamp the real skill version into the footer callout,
    regardless of what the model typed (`summarize-youtube-to-notion`,
    `...:<version>`, or a stale number). Rewrites only the `Generated by` token so
    the model-authored transcript-stats part of the footer is preserved."""
    ver = _skill_version()
    if not ver:
        return body_md
    return re.sub(
        r"(Generated by summarize-youtube-to-notion)(?::\S+)?",
        rf"\1:{ver}",
        body_md,
    )

# Growth Readings (marketing) DB — full-narrative home. Distinct from the AI
# Knowledge `Learnings/Growth Readings` DB written in Step 6 via record-knowledge.
DEFAULT_DB_ID = "2aa75e23af20801ebfbcf40645cb7469"
DEFAULT_DS_ID = "2aa75e23-af20-8020-8ec4-000bd69ced6d"

SOURCE_NAMES = ["Source", "URL", "Link", "YouTube", "YouTube URL"]
# The skill fills "today's / summarized date", so prefer a summarized-date column;
# fall back to other date columns by preference, then to any date property.
DATE_NAMES = ["Summarized Date", "Date Published", "Date Added", "Added", "Date", "Published"]

# Notion caps a page-create `children` array at 100 blocks; the rest are appended.
BLOCK_BATCH = 100


def _find(props: dict, candidates: list[str], types: tuple[str, ...]):
    """Return (name, type) of the first matching property by preference, then by type."""
    for name in candidates:
        meta = props.get(name)
        if meta and meta.get("type") in types:
            return name, meta["type"]
    for name, meta in props.items():
        if meta.get("type") in types:
            return name, meta["type"]
    return None, None


def resolve_data_source(db_id: str, ds_id: str):
    """Return (resolved_ds_id, properties_schema).

    Try the known data source id directly; if it drifted, resolve the current one
    from the database. Property names may have been renamed by the DB owner, so
    the schema is always read at runtime — never hardcoded.
    """
    try:
        ds = notion._request("GET", f"/data_sources/{ds_id}")  # noqa: SLF001
        return ds_id, ds.get("properties", {})
    except Exception:
        db = notion._request("GET", f"/databases/{db_id}")  # noqa: SLF001
        sources = db.get("data_sources") or []
        if sources:
            real = sources[0]["id"]
            ds = notion._request("GET", f"/data_sources/{real}")  # noqa: SLF001
            return real, ds.get("properties", {})
        return ds_id, db.get("properties", {})


def build_properties(schema: dict, title: str, source_url: str, date_iso: str):
    """Map canonical fields to whatever properties the data source actually has."""
    warnings: list[str] = []
    if not any(m.get("type") == "title" for m in schema.values()):
        raise SystemExit("ERROR: target data source has no title property; cannot create page.")

    # Under API 2025-09-03 with a data_source_id parent, the title must be keyed
    # by the literal property id "title" (lowercase), not its display name.
    props: dict = {"title": make_title(title)}

    src_name, src_type = _find(schema, SOURCE_NAMES, ("url", "rich_text"))
    if src_name:
        props[src_name] = {"url": source_url} if src_type == "url" else make_rich_text(source_url)
    else:
        warnings.append("no Source/URL property found — URL omitted from properties")

    if date_iso:
        date_name, _ = _find(schema, DATE_NAMES, ("date",))
        if date_name:
            props[date_name] = make_date(date_iso)
        else:
            warnings.append("no Date property found — date omitted from properties")

    return props, warnings


def main(argv=None) -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    p = argparse.ArgumentParser(description="Create a Growth Readings page via Notion REST.")
    p.add_argument("--markdown-file", required=True, help="Path to the composed summary body (Markdown).")
    p.add_argument("--title", required=True, help="Video title -> the page's title property.")
    p.add_argument("--source-url", required=True, help="Canonical YouTube URL.")
    p.add_argument("--date", default="", help="YYYY-MM-DD; omit to leave the date property empty.")
    p.add_argument("--db-id", default=DEFAULT_DB_ID, help="Override the target database id.")
    p.add_argument("--ds-id", default=DEFAULT_DS_ID, help="Override the target data source id.")
    p.add_argument("--icon", default="🎧", help="Page icon emoji.")
    p.add_argument("--dry-run", action="store_true", help="Print the block payload and exit; no write.")
    args = p.parse_args(argv)

    with open(args.markdown_file, encoding="utf-8") as f:
        body_md = f.read()
    body_md = _stamp_footer_version(body_md)   # ensure the footer carries the real metadata.version
    blocks = markdown_to_blocks(body_md)

    if args.dry_run:
        print(json.dumps({"block_count": len(blocks), "children": blocks}, ensure_ascii=False, indent=2))
        return 0

    if not notion.available:
        print(
            "ERROR: NOTION_TOKEN is not set. This skill is REST-only (no MCP fallback).\n"
            "Add NOTION_TOKEN to ~/.claude/settings.json env (see CLAUDE.md -> 'Notion REST "
            "integration') and restart Claude Code, or paste-export it in a Cowork session.",
            file=sys.stderr,
        )
        return 2

    ds_id, schema = resolve_data_source(args.db_id, args.ds_id)
    props, warnings = build_properties(schema, args.title, args.source_url, args.date)

    payload = {
        "parent": {"type": "data_source_id", "data_source_id": ds_id},
        "icon": {"type": "emoji", "emoji": args.icon},
        "properties": props,
        "children": blocks[:BLOCK_BATCH],
    }
    try:
        resp = notion._request("POST", "/pages", data=json.dumps(payload))  # noqa: SLF001
    except Exception as e:  # surface Notion's error body, which raise_for_status hides
        body = getattr(getattr(e, "response", None), "text", "")
        print(f"ERROR creating page: {e}\n{body}", file=sys.stderr)
        return 1

    page_id = resp["id"]
    for start in range(BLOCK_BATCH, len(blocks), BLOCK_BATCH):
        notion.append_block_children(page_id, blocks[start : start + BLOCK_BATCH])

    for w in warnings:
        print(f"warning: {w}", file=sys.stderr)
    print(resp.get("url", page_id))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
